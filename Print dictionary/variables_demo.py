# Variable assignments
student_name = "Samir"      # str
current_grade = 11         # int
attendance_pct = 95.5      # float
has_passed = True          # bool

# Printing variables with f-strings
print(f"Student: {student_name}")
print(f"Grade: Class {current_grade}")
print(f"Attendance: {attendance_pct}%")
print(f"Status Active: {has_passed}")

# Checking types using type()
print(f"Type of student_name: {type(student_name)}")
print(f"Type of current_grade: {type(current_grade)}")
